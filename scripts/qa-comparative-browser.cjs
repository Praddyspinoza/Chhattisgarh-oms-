"use strict";
const { chromium } = require("playwright-core");
const assert = require("node:assert/strict");
const fs = require("fs"),path=require("path");
const data=JSON.parse(fs.readFileSync("comparative_states_2026.json","utf8"));
const gov=JSON.parse(fs.readFileSync("comparative_government_2026.json","utf8"));
const exec=require("child_process").execSync;
let chrome=process.env.CHROME_PATH||"";
if(!chrome){try{chrome=exec("which google-chrome || which chromium || which chromium-browser",{encoding:"utf8"}).trim()}catch(e){throw Error("Chromium executable unavailable; browser QA cannot run")}}
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:chrome,args:["--no-sandbox","--disable-dev-shm-usage"]});
 let errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto("file://"+path.resolve("comparative.html"),{waitUntil:"load",timeout:30000});
  await page.waitForSelector("#dossierList .dossier-leader",{timeout:8000});
  assert.equal(await page.locator("#dossierList .dossier-leader").count(),6,"Initial dossier missing leaders");
  assert(await page.locator("#dossierList a.dossier-headline").count()>=15,"Initial report links not visible");
  const cartograms=page.locator("#omsCommandMap .cm-map-card");
  await page.waitForSelector("#omsCommandMap .cm-district",{timeout:9000});
  assert.equal(await cartograms.count(),3,"Missing 3 geographic district maps in dashboard command center");
  assert.equal(await page.locator("#omsCommandMap path.cm-polygon").count(),109,"Expected 109 named district nodes");
  await page.locator('#omsCommandMap [data-action="leader"][data-leader="mp-lop"]').click();
  await page.locator('#omsCommandMap [data-action="issue"][data-issue="Environment & Forests"]').click();
  assert(await page.locator("#omsCommandMap path.cm-hot").count()>=1,"Leader + issue filter should highlight district-level reporting");
  const katni=page.locator('#omsCommandMap path[data-state="Madhya Pradesh"][data-district="Katni"]');
  assert(await katni.evaluate(el=>el.classList.contains("cm-hot")),"Katni source-linked MP LoP/environment record not highlighted");
  await katni.click();
  assert(await page.locator("#omsCommandMap .cm-detail a[href*='timesofindia.indiatimes.com']").count()>=1,"Click district must open original source headlines");
  assert((await page.locator("#omsCommandMap .cm-detail").innerText()).includes("Katni"),"District dossier must identify selected district");
  await page.locator('#omsCommandMap [data-action="reset"]').first().click();
  assert.equal(await page.locator("#omsCommandMap path.cm-polygon").count(),109,"Map reset must keep all 109 geographic districts");
  await page.locator('#omsCommandMap [data-action="leader"][data-leader="mp-cm"]').click();
  await page.locator("#cmDistrictPicker").selectOption("Madhya Pradesh|Bhopal");
  assert.equal(await page.locator("#omsCommandMap .cm-issue-tile").count(),10,"Leader + district must show ten issue categories");
  assert(await page.locator("#omsCommandMap .cm-detail a[href^='https://']").count()>0,"Leader + district should show original report headlines across all issues");
  assert((await page.locator("#omsCommandMap .cm-detail").innerText()).includes("Bhopal"),"District panel should retain selected administrative district");
  assert(await page.locator("#omsCommandMap .cm-x-search").count()>=1,"Leader + district must provide date-scoped X discovery links");
  assert((await page.locator("#omsCommandMap .cm-x-search").first().getAttribute("href")).startsWith("https://x.com/search?"),"X discovery link must be identifiable as a search");
  await page.locator('#omsCommandMap [data-action="tab"][data-open-tab="official"]').click();
  assert.equal(await page.locator("#officialList a.institution-headline").count(),gov.officialRecords.length,"Quick official tab must show all source records");
  await page.locator('button.tab[data-tab="dossiers"]').click();
  const boxBefore=await page.locator('#omsCommandMap .cm-map-card').first().locator("svg").getAttribute("viewBox");
  await page.locator('#omsCommandMap [data-action="zoom"][data-state="Madhya Pradesh"][data-zoom="in"]').click();
  const boxAfter=await page.locator('#omsCommandMap .cm-map-card').first().locator("svg").getAttribute("viewBox");
  assert.notEqual(boxBefore,boxAfter,"Real map zoom button must change geographic viewport");
  assert.equal(await page.locator('.tabs [data-tab="official"]').count(),1,"Missing independent official-circulars tab");
  assert.equal(await page.locator('.tabs [data-tab="assembly"]').count(),1,"Missing independent Vidhan Sabha tab");
  await page.locator('#omsCommandMap [data-action="reset"]').first().click();
  assert.equal(await page.locator("#omsCommandMap .cm-map-card").count(),3,"Reset must preserve three-state map");
  await page.screenshot({path:"comparative-desktop-qa.png",fullPage:false});
  await page.locator('[data-dossier-topic="all"]').first().click();
  const all=await page.locator("#dossierList a.dossier-headline").count();
  assert.equal(all,data.records.length+data.posts.length,"Not all original source links are rendered in combined dossiers");
  const institutional=await page.locator("#dossierList a.institution-headline").count();
  assert.equal(institutional,gov.officialRecords.length+gov.assemblyRecords.length,"Government and assembly links absent from combined issue dossiers");
  const actualSourceLinks=await page.locator("#dossierList a.dossier-headline").evaluateAll(as=>as.map(a=>a.getAttribute("href")));
  for(const r of [...data.records,...data.posts])assert(actualSourceLinks.includes(r.url),"Missing original "+r.url);
  await page.locator('[data-dossier-topic="Mining"]').first().click();
  const count=await page.locator("#dossierList a.dossier-headline").count();
  assert.equal(count,data.records.filter(r=>r.issue==="Mining").length+data.posts.filter(r=>r.issue==="Mining").length);
  await page.locator('[data-dossier-topic="all"]').first().click();
  await page.locator('button[data-state="Odisha"]').first().click();
  assert.equal(await page.locator("#dossierList .dossier-leader").count(),20,"State filter should yield 2 leaders across 10 topics");
  await page.locator('button[data-state="all"]').first().click();
  await page.locator('button[data-role="Leader of Opposition"]').first().click();
  assert.equal(await page.locator("#dossierList .dossier-leader").count(),30,"Office filter should yield 3 leaders across 10 topics");
  await page.locator('button[data-role="all"]').first().click();
  await page.locator('button[data-tab="official"]').click();
  assert.equal(await page.locator("#officialList a.institution-headline").count(),gov.officialRecords.length,"Every departmental original link must be in the official tab");
  await page.locator('button[data-tab="assembly"]').click();
  assert.equal(await page.locator("#assemblyList a.institution-headline").count(),gov.assemblyRecords.length,"Every legislative original link must be in the assembly tab");
  assert.equal(await page.locator("#sessionList .panel").count(),3,"Missing three-state legislative session calendar");
  await page.locator('button[data-tab="social"]').click();
  const social=await page.locator("#postList a.source-headline").count();
  assert.equal(social,data.posts.length,"Social archive should include every original permalink");
  const target=await page.locator("#postList a.source-headline").first().getAttribute("href");
  assert(target.startsWith("https://x.com/")||target.startsWith("https://www.youtube.com/"),"Social headline links must be permalinks");
  await page.locator('button[data-tab="dossiers"]').click();
  await page.locator('[data-dossier-topic="Education, Healthcare & Employment"]').first().click();
  await page.screenshot({path:"comparative-issue-qa.png",fullPage:false});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator("#omsCommandMap .cm-map-card").count(),3,"Map must remain available on mobile");
  await page.screenshot({path:"comparative-map-mobile-qa.png",fullPage:false});
  assert.deepEqual(errors,[],"Browser JavaScript runtime errors");
  const main=await browser.newPage({viewport:{width:1366,height:860}});
  await main.goto("file://"+path.resolve("index.html"),{waitUntil:"domcontentloaded",timeout:30000});
  await main.waitForSelector("#oms-cmp-entry",{timeout:12000});
  await main.locator("#oms-cmp-entry").click({noWaitAfter:true});
  await main.waitForURL(/comparative\.html/,{waitUntil:"commit",timeout:18000});
  await main.waitForSelector("#dossierList .dossier-leader",{timeout:10000});
  await main.close();
  console.log(JSON.stringify({pass:true,chrome,defaultLeaders:6,totalDirectHeadlines:all,miningLinks:count,socialLinks:social,governmentLinks:gov.officialRecords.length,legislativeLinks:gov.assemblyRecords.length,integratedInstitutionLinks:institutional,scriptErrors:errors.length,mainNavigationToDossier:"pass",districtMaps:"3 actual-polygon maps / 109 districts",jointLeaderIssueFilter:"pass",districtSourceClick:"pass"},null,2));
 } finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
